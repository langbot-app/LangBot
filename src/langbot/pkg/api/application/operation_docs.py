def get_operation_doc(operation_id: str, *, side_effect: bool = False) -> OperationDoc:
    """Lookup operation documentation metadata, defaulting out-of-scope operations to exposure none."""
    doc = OPERATION_DOCS.get(operation_id)
    if doc is not None:
        return doc
    domain = operation_id.split('.')[0]
    domain_meta = DOMAINS.get(domain, {})
    label = domain_meta.get('label', {'zh_Hans': domain, 'en_US': domain.capitalize()})
    return OperationDoc(
        domain=domain,
        label=label,
        summary='',
        description='',
        risk='write' if side_effect else 'read',
        exposure='none',
    )
