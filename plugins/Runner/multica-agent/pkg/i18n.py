def normalize_language(language: typing.Any) -> str:
    """Return a supported locale code; anything else falls back to English."""
    return language if language in MESSAGES else DEFAULT_LANGUAGE


def get_text(language: typing.Any, key: str, /, **kwargs: typing.Any) -> str:
    """Render ``key`` in ``language``.

    Unknown locales and keys missing from a locale fall back to English; a key
    missing everywhere renders as the key itself, so the result is never empty.
    """
    template = MESSAGES[normalize_language(language)].get(key) or MESSAGES[DEFAULT_LANGUAGE].get(key) or key
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template
